/**
 * Returns course plan for a subject or generates a default template
 */
export function getCoursePlanForSubject(subjectCode: string, subjectName?: string): CoursePlan {
  const cleanCode = subjectCode ? subjectCode.toUpperCase().trim() : '';
  const cleanName = subjectName ? subjectName.toUpperCase().trim() : '';

  // 1. Direct key match in OFFICIAL_COURSE_PLANS
  if (OFFICIAL_COURSE_PLANS[cleanCode]) {
    return OFFICIAL_COURSE_PLANS[cleanCode];
  }

  // 2. Exact or alias matching for all Semester 1 courses:

  // Business Statistics (24GM14 / BS)
  if (cleanCode === 'BS' || cleanCode === '24GM14' || cleanName.includes('STATISTIC') || cleanName.includes('BUSINESS STAT')) {
    return OFFICIAL_COURSE_PLANS['24GM14'];
  }

  // Accounting for Decision Making (24GM13 / ADM)
  if (cleanCode === 'ADM' || cleanCode === '24GM13' || cleanCode === '24GW14' || cleanName.includes('ACCOUNTING') || cleanName.includes('ADM')) {
    return OFFICIAL_COURSE_PLANS['24GM13'];
  }

  // Spreadsheet Applications (24GM16 / SSA)
  if (cleanCode === 'SSA' || cleanCode === '24GM16' || cleanName.includes('SPREADSHEET') || cleanName.includes('EXCEL')) {
    return OFFICIAL_COURSE_PLANS['24GM16'];
  }

  // Management Concepts & Organizational Behaviour (24GM11 / MCOB)
  if (cleanCode === 'MCOB' || cleanCode === '24GM11' || cleanName.includes('ORGANIZATIONAL') || cleanName.includes('MANAGEMENT CONCEPTS') || cleanName.includes('MCOB')) {
    return OFFICIAL_COURSE_PLANS['24GM11'];
  }

  // Economics for Decision Making (24GM12 / EDM)
  if (cleanCode === 'EDM' || cleanCode === '24GM12' || cleanName.includes('ECONOMICS') || cleanName.includes('EDM')) {
    return OFFICIAL_COURSE_PLANS['24GM12'];
  }

  // Managerial Communication (24GM15 / MC)
  if (cleanCode === 'MC' || cleanCode === '24GM15' || cleanName.includes('COMMUNICATION') || cleanName.includes('MANAGERIAL COMM')) {
    return OFFICIAL_COURSE_PLANS['24GM15'];
  }

  // Legal Aspects of Business (24GM19 / LA)
  if (cleanCode === 'LA' || cleanCode === '24GM19' || cleanName.includes('LEGAL') || cleanName.includes('LAW')) {
    return OFFICIAL_COURSE_PLANS['24GM19'];
  }

  // Social Sensitization for Managers (24GM18 / SSM)
  if (cleanCode === 'SSM' || cleanCode === '24GM18' || cleanName.includes('SOCIAL') || cleanName.includes('SENSITIZATION')) {
    return OFFICIAL_COURSE_PLANS['24GM18'];
  }

  // 3. Fallback generic template
  return {
    subjectCode: cleanCode || 'MBA-COURSE',
    subjectTitle: subjectName || cleanCode || 'MBA Course',
    semester: 'I',
    batch: 'MBA',
    mode: 'CA & FE',
    faculty: ['PSGIM Faculty Coordinator'],
    courseObjective: `Master core concepts, analytical frameworks, and managerial applications in ${subjectName || cleanCode}.`,
    caMaxMarks: 50,
    feMaxMarks: 50,
    assessments: [
      {
        id: `ca_${cleanCode.toLowerCase()}_1`,
        title: 'Continuous Assessment 1 (Assignment / Case Study)',
        type: 'GROUP_ACTIVITY',
        scheduledDate: 'Mid Semester',
        sessionsCovered: 'Unit 1 & 2',
        marksAllotted: 10,
        description: 'Case analysis, practical project, or seminar presentation.',
      },
      {
        id: `ca_${cleanCode.toLowerCase()}_mid`,
        title: 'Mid Term Test',
        type: 'EXAM',
        scheduledDate: 'September 21–23, 2026',
        sessionsCovered: 'Unit 1 & 2',
        marksAllotted: 20,
        description: 'Summative written examination evaluating conceptual grasp (Wrote for 50 marks, converted to 20 marks).',
      },
      {
        id: `ca_${cleanCode.toLowerCase()}_2`,
        title: 'Continuous Assessment 2 (Quiz / Lab / Field Work)',
        type: 'INDIVIDUAL_LAB',
        scheduledDate: 'Late Semester',
        sessionsCovered: 'Unit 3 & 4',
        marksAllotted: 10,
        description: 'Practical evaluation, quiz, or individual assignment.',
      },
      {
        id: `ca_${cleanCode.toLowerCase()}_case`,
        title: 'Case Study / End Term Seminar',
        type: 'CASE_ANALYSIS',
        scheduledDate: 'Final Weeks',
        sessionsCovered: 'Unit 5',
        marksAllotted: 10,
        description: 'Comprehensive business case analysis and managerial synthesis.',
      },
    ],
    sessions: Array.from({ length: 30 }, (_, i) => ({
      sessionNumber: i + 1,
      unit: i < 6 ? 'Unit I' : i < 12 ? 'Unit II' : i < 18 ? 'Unit III' : i < 24 ? 'Unit IV' : 'Unit V',
      topic: `${subjectName || cleanCode} – Lecture Session ${i + 1}`,
      isExam: i === 12 || i === 13,
    })),
    classroomRules: [
      '📖 Regular attendance and punctuality are required for all sessions.',
      '💻 Bring laptop whenever analytical or case discussion is scheduled.',
      '🤝 Active class participation in case analysis is mandatory.',
    ],
    recommendedBooks: [
      `Standard Textbooks for ${subjectName || cleanCode} (PSGIM Library Reference)`,
    ],
  };
}
